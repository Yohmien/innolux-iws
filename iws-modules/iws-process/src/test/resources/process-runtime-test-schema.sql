    id bigint NOT NULL PRIMARY KEY,
    instance_id bigint NULL, system_code varchar(64) NULL, posting_mode varchar(24) NULL,
    first_confirmed tinyint(1) NULL, confirmed_by bigint NULL, confirmed_name varchar(128) NULL,
    confirmed_at datetime(3) NULL, revision bigint NULL,
    create_dept bigint NULL, create_by bigint NULL, create_time datetime(3) NULL,
