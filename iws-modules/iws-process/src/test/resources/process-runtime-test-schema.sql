) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE iws_process_trigger_receipt (
    id bigint NOT NULL PRIMARY KEY,
    caller_system_code varchar(64) NULL, module_code varchar(64) NULL,
    call_contract_key varchar(128) NULL, call_contract_version varchar(32) NULL,
    source_request_id varchar(128) NULL, payload_hash varchar(128) NULL,
    effect_key varchar(256) NULL, logical_call_key varchar(256) NULL,
    instance_id bigint NULL, event_id bigint NULL, external_task_id varchar(128) NULL,
    origin_outbound_event_id bigint NULL, purpose varchar(32) NULL,
    canonical tinyint(1) NULL, processing_status varchar(32) NULL,
    ack_summary varchar(500) NULL, evidence_summary varchar(1000) NULL,
    received_at datetime(3) NULL, applied_at datetime(3) NULL,
    create_dept bigint NULL, create_by bigint NULL, create_time datetime(3) NULL,
    update_by bigint NULL, update_time datetime(3) NULL,
    UNIQUE KEY uk_test_receipt (caller_system_code, call_contract_key, call_contract_version, source_request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE runtime_test_effect (
    id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY,
    event_id bigint NOT NULL,
    effect_key varchar(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
