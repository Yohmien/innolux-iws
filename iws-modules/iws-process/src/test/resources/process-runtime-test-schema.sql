-- 运行层隔离测试结构；只用于 iws_process_runtime_test 库。
DROP TABLE IF EXISTS iws_process_trigger_receipt;
DROP TABLE IF EXISTS iws_process_system_context;
DROP TABLE IF EXISTS iws_process_schedule_control;
DROP TABLE IF EXISTS iws_process_attempt;
DROP TABLE IF EXISTS iws_process_token;
DROP TABLE IF EXISTS iws_process_event;
DROP TABLE IF EXISTS iws_process_instance;
DROP TABLE IF EXISTS runtime_test_effect;

CREATE TABLE iws_process_instance (
    id bigint NOT NULL PRIMARY KEY,
    plan_role varchar(16) NULL,
    definition_version_id bigint NOT NULL,
    definition_revision bigint NULL,
    schedule_id bigint NULL,
    plan_type varchar(64) NULL,
    business_schedule_code varchar(64) NULL,
    supervisor_instance_id bigint NULL,
    supervisor_key varchar(256) NULL,
    business_task_key varchar(256) NULL,
    business_type varchar(64) NULL,
    business_id varchar(128) NULL,
    task_key varchar(128) NULL,
    schedule_scope varchar(128) NULL,
    mode_snapshot varchar(16) NULL,
    hold_start tinyint(1) NULL,
    first_admitted_at datetime(3) NULL,
    plan_status varchar(32) NULL,
    instance_priority int NULL,
    selected_root_set text NULL,
    input_hash varchar(128) NULL,
    execution_deadline datetime(3) NULL,
    round_no bigint NULL,
    stop_requested tinyint(1) NULL,
    cancel_requested tinyint(1) NULL,
    exception_summary varchar(1000) NULL,
    started_at datetime(3) NULL,
    ended_at datetime(3) NULL,
    instance_version bigint NULL,
    create_dept bigint NULL, create_by bigint NULL, create_time datetime(3) NULL,
    update_by bigint NULL, update_time datetime(3) NULL,
    UNIQUE KEY uk_test_instance_supervisor (supervisor_key),
    UNIQUE KEY uk_test_instance_business (business_task_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE iws_process_event (
    id bigint NOT NULL PRIMARY KEY,
    instance_id bigint NULL,
    token_id bigint NULL,
    definition_version_id bigint NULL,
    event_definition_id bigint NULL,
    event_code varchar(64) NULL,
    event_key varchar(255) NULL,
    round_no bigint NULL,
    branch_identity varchar(255) NULL,
    event_role varchar(16) NULL,
    event_direction varchar(16) NULL,
    system_code varchar(64) NULL,
    call_contract_key varchar(128) NULL,
    call_contract_version varchar(32) NULL,
    local_action_key varchar(128) NULL,
    local_action_version varchar(32) NULL,
    effect_key varchar(128) NULL,
    local_effect_key varchar(128) NULL,
    source_state_code varchar(64) NULL,
    target_state_code varchar(64) NULL,
    event_status varchar(32) NULL,
    wait_reason varchar(32) NULL,
    outcome varchar(32) NULL,
    effect_result varchar(32) NULL,
    sent tinyint(1) NULL,
    payload_ready tinyint(1) NULL,
    input_hash varchar(128) NULL,
    idempotency_key varchar(255) NULL,
    origin_outbound_event_id bigint NULL,
    recovery_for_event_code varchar(64) NULL,
    execution_purpose varchar(32) NULL,
    priority int NULL,
    next_retry_time datetime(3) NULL,
    retry_count int NULL,
    owner varchar(128) NULL,
    lease_epoch bigint NULL,
    lease_until datetime(3) NULL,
    event_version bigint NULL,
    started_at datetime(3) NULL,
    ended_at datetime(3) NULL,
    last_attempt_id bigint NULL,
    recovery_requested tinyint(1) NULL,
    recovery_deadline datetime(3) NULL,
    error_code varchar(64) NULL,
    error_message varchar(1000) NULL,
    create_dept bigint NULL, create_by bigint NULL, create_time datetime(3) NULL,
    update_by bigint NULL, update_time datetime(3) NULL,
    UNIQUE KEY uk_test_event_key (instance_id, event_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE iws_process_attempt (
    id bigint NOT NULL PRIMARY KEY,
    event_id bigint NULL,
    attempt_no int NULL,
    resume_from_attempt_id bigint NULL,
    checkpoint_status varchar(32) NULL,
