package com.innolux.iws.common.encrypt.properties;

import lombok.Data;
import com.innolux.iws.common.encrypt.enums.AlgorithmType;
import com.innolux.iws.common.encrypt.enums.EncodeType;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * 加解密属性配置类
 *
 * @author YONGJIE.PENG
 * @version 4.6.0
 */
@Data
@ConfigurationProperties(prefix = "mybatis-encryptor")
public class EncryptorProperties {

    /**
     * 过滤开关
     */
    private Boolean enable;

    /**
     * 默认算法
     */
    private AlgorithmType algorithm = AlgorithmType.BASE64;

    /**
     * 安全秘钥
     */
    private String password;

    /**
     * 公钥
     */
    private String publicKey;

    /**
     * 私钥
     */
    private String privateKey;

    /**
     * 编码方式，base64/hex
     */
    private EncodeType encode = EncodeType.BASE64;

}
